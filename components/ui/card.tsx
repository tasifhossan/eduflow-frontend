  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn('flex items-center p-6 pt-0 mt-auto', className)}
    {...props}
  />
));
CardFooter.displayName = 'CardFooter';
